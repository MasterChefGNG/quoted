// Copies the Android app's quotes.json into js/quotes.js so both apps share one source of truth.
// Run from quoted-web: node tools/build-quotes.mjs
import { readFileSync, writeFileSync } from 'node:fs';
const src = new URL('../../quoted/app/src/main/assets/quotes.json', import.meta.url);
const quotes = JSON.parse(readFileSync(src, 'utf8'));
writeFileSync(new URL('../js/quotes.js', import.meta.url),
  `// Generated by tools/build-quotes.mjs from the Android app's quotes.json. Do not edit by hand.\nexport const QUOTES = ${JSON.stringify(quotes, null, 1)};\n`);
console.log(`${quotes.length} quotes written`);
